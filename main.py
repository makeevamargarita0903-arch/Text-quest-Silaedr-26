tests = 0
books = 0
inventory = {}


def add_item(name):
    inventory[name] = inventory.get(name, 0) + 1
    print(f'[Инвентарь] Ты подобрал: {name}')
    time.sleep(1.5)


def get_choice(prompt, options):
    while True:
        c = input(prompt).strip()
        if c in options:
            return c
        print(f'Пожалуйста, выбери из: {", ".join(options)}')
        time.sleep(1)


