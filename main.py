def hub_scene():
    """Хаб: игрок выбирает, чем заняться. Может возвращаться сюда из других сцен."""
    print('\nТы дома. Что хочешь сделать?')
    time.sleep(1)
    print('1) Попробовать забрать компьютер у родителей')
    print('2) Продолжить читать книгу')
    print('3) Лечь спать и закончить день')
    time.sleep(1.5)
    c4 = get_choice('Твой выбор: ', ['1', '2', '3'])
    if c4 == '1':
        steal_scene()
    elif c4 == '2':
        read_scene()
    else:
        print('Ты решил лечь спать. Завтра будет новый день.')
        time.sleep(2)
        final_scene(tests, inventory)


